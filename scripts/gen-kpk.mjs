// Regenerates lib/learn/kpk-data.ts (the K+P vs K table) from scratch.  Run: node scripts/gen-kpk.mjs
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { solve, packTable } from '../lib/learn/kpk.ts';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'learn', 'kpk-data.ts');
const t = solve();
let wins = 0;
for (const v of t) wins += v;
const text = "// Generated by scripts/gen-kpk.mjs. The validator re-solves and compares.\nexport const KPK_B64 = '" + packTable(t) + "';\n";
writeFileSync(out, text);
console.log('wrote', out, wins, 'winning states');
