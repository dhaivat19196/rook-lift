export function gameLesson(g: MasterGame) {
  return lesson({
    id: 'game-' + g.id,
    title: g.title,
    blurb: `${g.white.split(' ').slice(-1)[0]} vs ${g.black.split(' ').slice(-1)[0]}, ${g.year}. ${g.theme.charAt(0).toUpperCase() + g.theme.slice(1)}.`,
    mins: 12,
    intro: `We are going to look at a famous game together. ${g.blurb} As you step through it, look for: ${g.theme}.`,
    rule: g.rule,
    habit: g.habit,
    recap: g.recap,
    steps: [
      ...ph('example', txt(g.title, `${g.blurb}\n\n**${g.white}** against **${g.black}**, ${g.year}. ${g.event}.\n\nWatch first, with the comments. Then try to guess the moves.`, B(START_FEN))),
      { t: 'game' as const, gameId: g.id, mode: 'watch' as const, phase: 'example' as const },
      { t: 'game' as const, gameId: g.id, mode: 'guess' as const, phase: 'practice' as const },
      ...ph('practice', choice(g.ask.q, [o(g.ask.ok, true), ...g.ask.wrong.map((w) => o(w))], g.ask.why, undefined, { reasoning: true })),
    ],
  });
}

const byLevel = (n: number) => GAMES.filter((g) => g.level === n);

