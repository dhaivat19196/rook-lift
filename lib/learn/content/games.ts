/** The position BEFORE the move at `ply` (1-based) of a master game, for tactics practice taken from real games. */
export function gameFen(id: string, ply: number): string {
  const g = GAMES.find((x) => x.id === id);
  if (!g) throw new Error('unknown game ' + id);
  const c = new Chess();
  c.loadPgn(g.pgn);
  const h = c.history({ verbose: true });
  return h[ply - 1].before;
}

